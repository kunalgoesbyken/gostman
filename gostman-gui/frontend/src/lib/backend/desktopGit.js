import {
  GitAbortMerge,
  GitAddRemote,
  GitBranches,
  GitClone,
  GitCommit,
  GitConflict,
  GitCreateBranch,
  GitDeleteBranch,
  GitDiff,
  GitDiscard,
  GitFetch,
  GitInit,
  GitLog,
  GitOpenPullRequest,
  GitPull,
  GitPush,
  GitResolve,
  GitRestoreVersion,
  GitSetRemoteURL,
  GitStage,
  GitStageAll,
  GitStashAction,
  GitStashSave,
  GitStashes,
  GitState,
  GitSwitchBranch,
  GitUnstage,
  GitVersion,
} from '../../../wailsjs/go/main/App'

export const desktopGit = {
  state: () => GitState(),
  diff: (path, staged, untracked) => GitDiff(path, staged, untracked),
  stage: (paths) => GitStage(paths),
  stageAll: () => GitStageAll(),
  unstage: (paths) => GitUnstage(paths),
  discard: (path, untracked) => GitDiscard(path, untracked),
  commit: (message, stageAll) => GitCommit(message, stageAll),
  fetch: () => GitFetch(),
  pull: () => GitPull(),
  push: () => GitPush(),
  branches: () => GitBranches(),
  createBranch: (name) => GitCreateBranch(name),
  switchBranch: (name, remote) => GitSwitchBranch(name, remote),
  deleteBranch: (name, force) => GitDeleteBranch(name, force),
  stashes: () => GitStashes(),
  saveStash: (message) => GitStashSave(message),
  stashAction: (action, index) => GitStashAction(action, index),
  log: (path) => GitLog(path),
  version: (hash, path) => GitVersion(hash, path),
  restoreVersion: (hash, path) => GitRestoreVersion(hash, path),
  conflict: (path) => GitConflict(path),
  resolve: (path, content) => GitResolve(path, content),
  abortMerge: () => GitAbortMerge(),
  init: () => GitInit(),
  clone: (url, parent) => GitClone(url, parent),
  addRemote: (name, url) => GitAddRemote(name, url),
  setRemoteUrl: (name, url) => GitSetRemoteURL(name, url),
  openPullRequest: () => GitOpenPullRequest(),
}
